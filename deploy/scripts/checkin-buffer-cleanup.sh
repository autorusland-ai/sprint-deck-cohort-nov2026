#!/usr/bin/env bash
# Убирает буфер вечернего чек-ина, когда сам чек-ин уже записан.
#
# Зачем скриптом, а не правилом боту: удаление буфера — последний шаг диалога,
# и модель его регулярно пропускает (проверено на прогонах 31.08.2026). Забытый
# буфер за прошлую дату сессии читают как «чек-ин не сдан» — так уже дважды
# получался ложный сигнал в разборе дня.
#
# Логика простая и безопасная: буфер удаляется ТОЛЬКО если за его дату есть
# готовый файл чек-ина. Нет файла — буфер остаётся, это и есть его назначение
# (сигнал «опрос начат, но не закрыт»).
set -u

BUF=/home/clawd/emmbase/inbox/_чекин-в-процессе.md
DIR=/home/clawd/emmbase/life/чекины
LOG=/home/clawd/.openclaw/logs/checkin-buffer.log
mkdir -p "$(dirname "$LOG")"
ts() { date -u '+%Y-%m-%dT%H:%M:%SZ'; }

[ -f "$BUF" ] || exit 0

# Дата берётся из заголовка буфера: «## Чекин ГГГГ-ММ-ДД»
DATE=$(grep -oE '[0-9]{4}-[0-9]{2}-[0-9]{2}' "$BUF" 2>/dev/null | head -1)
if [ -z "$DATE" ]; then
    echo "$(ts) [skip] в буфере нет даты — не трогаю" >> "$LOG"
    exit 0
fi

if [ -f "$DIR/$DATE.md" ]; then
    rm -f "$BUF"
    echo "$(ts) [ok] чек-ин за $DATE записан — буфер удалён" >> "$LOG"
else
    # Буфер старше суток без готового чек-ина — опрос сорвался. Не удаляем,
    # но отмечаем в логе: это материал для разбора, а не норма.
    if [ -n "$(find "$BUF" -mmin +1440 2>/dev/null)" ]; then
        echo "$(ts) [stale] буфер за $DATE висит больше суток, чек-ина нет" >> "$LOG"
    fi
fi

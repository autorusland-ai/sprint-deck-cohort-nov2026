PROMPT="???????????????? ?????????? memory/ ???? ?????????????? 7 ????????: \n\n$CONTENT\n\n????????????????: 3-5 ???????????????? ??????, 5 ????????????, 3 ??????????????, action items ???? ?????????????????? ????????????. ?????? ?????????????????? ?????? ???????????? ????????."

DIGEST=$(openclaw execute --model openrouter/moonshotai/kimi-k2.6 "$PROMPT")


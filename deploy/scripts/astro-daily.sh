#!/usr/bin/env bash
# Выкладывает расчёт транзитов и Бацзы в базу знаний перед утренним прогнозом.
#
# Зачем файл, а не вызов из бота: cron-задача выполняется в песочнице, которая
# host-скрипты не видит и в сеть не ходит. Зато /emmbase туда примонтирован —
# поэтому данные кладём файлом, а бот их просто читает.
#
# Почему не из интернета: астрологические сайты закрыты Cloudflare и отдают 403
# на автоматический сбор. Без источника модель начинала выдавать градусы «по
# памяти» — цифры, неотличимые от выдуманных. Здесь всё считается из эфемерид.
set -u

OUT=/home/clawd/emmbase/life/прогнозы/_астро-данные-сегодня.md
CLI=/home/clawd/.openclaw/scripts/astro-cli.py
mkdir -p "$(dirname "$OUT")"

{
  echo "# Астро-данные на $(date +%d.%m.%Y) — расчёт, не из интернета"
  echo
  echo "> Считает \`astro-cli.py\` из эфемерид прямо на VPS: натальная карта от"
  echo "> 05.05.1971 17:05 (Уссурийск, UTC+10), транзиты на 09:00 МСК."
  echo "> Сверено с \`life/прогнозирование.md\` — совпадает до угловых минут."
  echo "> Обновляется ежедневно в 04:50 МСК, перед утренним прогнозом."
  echo
  echo '```'
  "$CLI" all 2>&1
  echo '```'
} > "$OUT.tmp" && mv "$OUT.tmp" "$OUT"
